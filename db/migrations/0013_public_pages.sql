-- Public quote and form pages (served from the UI's /p/quote/ and /p/form/,
-- backed by the unauthenticated /v1/public/* API routes).
--
-- Quotes and forms get a random public_key (base64url) that goes in the page
-- URL; it is never the sequential record id, so links cannot be guessed.
-- Regenerating a quote's key revokes the old link. Customers accept or decline
-- a quote through the API, which fills the responded_* properties.
-- Form submissions record where they came from.

select meta.create_property(
  p_object => 'quotes', p_api_name => 'public_key', p_label => 'Public key', p_type => 'text',
  p_options => '{"single_line": true, "unique": true, "regex": "^[A-Za-z0-9_-]{22,64}$"}',
  p_description => 'Secret part of the customer link (/p/quote/#key). Set and regenerated by the API.', p_is_native => true);
select meta.create_property(
  p_object => 'quotes', p_api_name => 'responded_at', p_label => 'Responded at', p_type => 'datetime',
  p_description => 'When the customer accepted or declined the quote.', p_is_native => true);
select meta.create_property(
  p_object => 'quotes', p_api_name => 'responder_name', p_label => 'Responder name', p_type => 'text',
  p_options => '{"single_line": true}', p_is_native => true);
select meta.create_property(
  p_object => 'quotes', p_api_name => 'responder_email', p_label => 'Responder email', p_type => 'text',
  p_options => '{"single_line": true}', p_is_native => true);
select meta.create_property(
  p_object => 'quotes', p_api_name => 'decline_reason', p_label => 'Decline reason', p_type => 'text', p_is_native => true);

select meta.create_property(
  p_object => 'forms', p_api_name => 'public_key', p_label => 'Public key', p_type => 'text',
  p_options => '{"single_line": true, "unique": true, "regex": "^[A-Za-z0-9_-]{22,64}$"}',
  p_description => 'Identifies the form on the hosted page (/p/form/#key) and in the embed snippet. Set by the API.', p_is_native => true);

select meta.create_property(
  p_object => 'form_submissions', p_api_name => 'origin', p_label => 'Origin', p_type => 'text',
  p_options => '{"single_line": true}', p_description => 'Website the form was submitted from (the browser''s Origin header).', p_is_native => true);
select meta.create_property(
  p_object => 'form_submissions', p_api_name => 'ip_address', p_label => 'IP address', p_type => 'text',
  p_options => '{"single_line": true}', p_is_native => true);
select meta.create_property(
  p_object => 'form_submissions', p_api_name => 'user_agent', p_label => 'User agent', p_type => 'text',
  p_options => '{"single_line": true}', p_is_native => true);

-- Websites allowed to post forms, as origins ("https://www.example.com").
-- The UI's own origin is always allowed (hosted form page).
insert into ui.settings (key, value) values ('forms', '{"allowed_origins": []}') on conflict (key) do nothing;
