-- Online payments for quotes and invoices (docs/architecture.md "Payments").
-- Each tenant gets a Stripe account (Connect, Accounts v2) made by ProfitPad's
-- platform; customers pay on Stripe Checkout from the public quote and invoice
-- pages, and a Stripe webhook records the payment. Interac e-Transfers are
-- handled by hand: the customer says they sent one (a pending payment) and
-- staff confirm it when the money arrives.

-- ---- Stripe connection ---------------------------------------------------------

-- The tenant's Stripe account. Only the account id is stored: the API calls
-- Stripe with the platform key and the Stripe-Account header.
create table auth.payment_connections (
  id bigserial primary key,
  provider text not null check (provider in ('stripe')),
  account_id text not null unique,
  link_method text not null check (link_method in ('accounts_v2')),
  livemode boolean not null,
  country text not null check (country ~ '^[A-Z]{2}$'),
  status text not null default 'onboarding' check (status in ('onboarding', 'active', 'restricted', 'removed')),
  -- what Stripe still needs (requirements summary from the account)
  requirements jsonb not null default '{}',
  connected_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index payment_connections_one_live on auth.payment_connections (provider) where status <> 'removed';

-- One row per Stripe Checkout Session the API created, so an open session can
-- be reused and a webhook can find the record it pays for.
create table auth.stripe_checkout_sessions (
  session_id text primary key,
  account_id text not null,
  object text not null check (object in ('quotes', 'invoices')),
  record_id text not null,
  purpose text not null check (purpose in ('invoice', 'quote_deposit', 'quote_full')),
  amount_minor bigint not null check (amount_minor > 0),
  currency text not null,
  url text not null,
  status text not null default 'open' check (status in ('open', 'complete', 'failed', 'expired')),
  payment_record_id text,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index stripe_checkout_sessions_record_idx on auth.stripe_checkout_sessions (object, record_id);

-- Webhook events already handled (Stripe may deliver one more than once).
create table auth.stripe_events (
  event_id text primary key,
  type text not null,
  account text,
  received_at timestamptz not null default now()
);

