-- Descriptions for every built-in property, shown as a tooltip when people
-- hover a property's label (and in Settings, Properties).
--
-- 1. System properties every object has (record ID, object type, name,
--    created and updated at, merged IDs): filled now on every object, and by
--    the trigger fill_base_description for objects created later. Created by
--    and updated by already had theirs (meta._actor_description).
-- 2. The CRM's own properties (is_native).
-- 3. The defense package's properties, on tenants that have it installed
--    (meta.packages). The package installer never changes existing
--    properties, so this is how the defense CRM gets them; new installs get
--    them from api/packages/defense/manifest.json.
-- Only empty descriptions are filled: one someone wrote is kept.

create function meta._base_property_description(p_api_name text, p_type text) returns text
  language sql immutable
  set search_path to 'pg_catalog', 'public', 'pg_temp'
  as $$
  select case
    when p_type = 'id' then 'The record''s unique ID, set by the CRM when the record is created. Used in links, imports and the API.'
    when p_api_name = 'object_type_id' then 'The code of the object the record belongs to (pc_0012 for deals). Set by the CRM.'
    when p_api_name = 'name' and p_type = 'calculation' then 'The record''s name, worked out from its other properties. Shown in lists, search and links to the record.'
    when p_api_name = 'name' then 'The record''s name, shown in lists, search and links to the record.'
    when p_api_name = 'created_at' then 'When the record was created. A different date can be given when creating it, as imports may do.'
    when p_api_name = 'updated_at' then 'When the record last changed. Set by the CRM.'
    when p_api_name = 'merged_ids' then 'IDs of the records merged into this one. Links and searches for those IDs find this record.'
  end
$$;

alter function meta._base_property_description(text, text) owner to pc_migrator;

create function meta._fill_base_description() returns trigger
  language plpgsql
  set search_path to 'pg_catalog', 'public', 'pg_temp'
  as $$
begin
  if new.is_base and coalesce(new.description, '') = '' then
    new.description := meta._base_property_description(new.api_name, new.type);
  end if;
  return new;
end $$;

alter function meta._fill_base_description() owner to pc_migrator;

